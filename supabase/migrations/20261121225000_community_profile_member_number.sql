-- Stable public community member numbers for profile cards and identity previews.
-- Existing rows receive deterministic unique values from a database identity sequence.
alter table public.community_member_profiles
  add column if not exists member_number bigint generated by default as identity;

create unique index if not exists community_member_profiles_member_number_uidx
  on public.community_member_profiles(member_number);

alter table public.community_member_profiles
  drop constraint if exists community_member_profiles_member_number_positive_check;

alter table public.community_member_profiles
  add constraint community_member_profiles_member_number_positive_check
  check (member_number > 0);

comment on column public.community_member_profiles.member_number is
  'Stable unique public identifier used by community member profiles. Not an authentication identifier.';